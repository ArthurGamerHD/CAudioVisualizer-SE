namespace SeAudioVisualizer.Core
{
    public struct Color3
    {
        public float X;
        public float Y;
        public float Z;

        public Color3(float x, float y, float z)
        {
            X = x;
            Y = y;
            Z = z;
        }
    }

    public struct Point2
    {
        public float X;
        public float Y;

        public Point2(float x, float y)
        {
            X = x;
            Y = y;
        }
    }
}
